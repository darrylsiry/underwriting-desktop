import type { SubjectivityStatus } from "./bind-rules";
import { MUTED, createDocument, masthead, money, parties, premiumBlock, surplusLinesNotice, usDate, type Writer } from "./pdf-writer.ts";   // .ts so node:test can load this module
import { todayIso } from "./time.ts";

export type PolicyDocument = {
  policyNumber: string;
  binderNumber: string;
  quoteNumber: string;
  quoteVersion: number;
  boundAt: Date;
  boundBy: string;
  insuredName: string;
  insuredAddress: string[];
  producer: string[];
  effectiveDate: string;
  expirationDate: string;
  limits: { label: string; amount: number }[];
  deductible: number;
  classCode: string;
  classDescription: string;
  operations: string;
  states: string[];
  grossReceipts: number;
  premium: number;
  policyFee: number;
  surplusLinesTax: number;
  surplusLinesTaxRate: number;
  homeState: string;
  total: number;
  rateVersion: string;
  subjectivities: SubjectivityStatus[];
  forms: string[];
};

const FOOTER = "Illustrative document generated by Underwriting Desktop for demonstration only. Not evidence of insurance.";

function limitsBlock(w: Writer, p: PolicyDocument) {
  for (const l of p.limits) w.row(l.label, money(l.amount));
  w.row("Deductible (bodily injury and property damage, per occurrence)", p.deductible ? money(p.deductible) : "None");
}

const STATUS_COLUMN = 110;   // room for "OPEN - due 12/31/2026" in bold at 9pt

/** CR-109: the underwriter's free text wraps clear of its status, so a long one can't overprint it or run off the page. */
export function subjectivitiesBlock(w: Writer, subjectivities: SubjectivityStatus[]) {
  for (const [i, s] of subjectivities.entries()) {
    const status = s.status === "received" ? "Received" : `OPEN - due ${usDate(s.due_date!)}`;
    w.ensure(14);
    w.text(status, { right: 558, size: 9, bold: s.status === "open" });
    w.para(`${i + 1}.  ${s.text}`, { size: 9, width: 558 - STATUS_COLUMN - 54 });
    w.y -= 2;
  }
}

/** One-page binder: temporary evidence that coverage is bound, with any open subjectivities. */
export async function renderBinderPdf(p: PolicyDocument): Promise<Uint8Array> {
  const { doc, w } = await createDocument({
    title: `Binder ${p.binderNumber} - ${p.insuredName}`,
    subject: "Commercial General Liability binder (illustrative)",
    footer: `${FOOTER} ${p.binderNumber}  ·  Rated on rate version ${p.rateVersion}`,   // UX-016
  });
  masthead(w, {
    reference: `Binder ${p.binderNumber}`,
    title: "Binder of Insurance",
    subtitle: "Commercial General Liability  ·  Excess & surplus lines",
    right: [`Bound ${usDate(todayIso(p.boundAt))} by ${p.boundBy}`, `Policy ${p.policyNumber} to follow`],
  });
  parties(w, "Named insured and producer", [p.insuredName, ...p.insuredAddress], p.producer);

  w.heading("Binder period");
  w.para(`Coverage is bound effective ${usDate(p.effectiveDate)} at 12:01 a.m. standard time and continues until the policy `
    + `is issued or 30 days, whichever comes first. Policy period ${usDate(p.effectiveDate)} to ${usDate(p.expirationDate)}.`);

  w.heading("Coverage and limits (occurrence form)");
  limitsBlock(w, p);
  w.row("Class", `${p.classCode}  ${p.classDescription}`);
  w.row("Premium basis", `Gross receipts ${money(p.grossReceipts)}`);

  w.heading("Premium");
  premiumBlock(w, p);

  w.heading("Subjectivities");
  subjectivitiesBlock(w, p.subjectivities);
  const open = p.subjectivities.filter((s) => s.status === "open").length;
  w.y -= 4;
  w.para(open
    ? `Coverage is bound subject to the ${open} open subjectivit${open === 1 ? "y" : "ies"} above. If they are not received `
      + "by the due date, the company may amend or cancel coverage in line with the policy conditions."
    : "All subjectivities have been received.", { size: 8.5, color: MUTED });

  w.heading("Terms");
  w.para(`Bound on the terms, conditions and forms of quotation ${p.quoteNumber} version ${p.quoteVersion}, `
    + "which is part of this binder.", { size: 8.5 });

  w.y -= 18;
  w.text(`Authorized representative: ${p.boundBy}`, { size: 9 });
  w.y -= 8;
  surplusLinesNotice(w);
  return doc.save();
}

/** Policy document: declarations, classification and forms schedules, abridged conditions. */
export async function renderPolicyPdf(p: PolicyDocument): Promise<Uint8Array> {
  const { doc, w } = await createDocument({
    title: `Policy ${p.policyNumber} - ${p.insuredName}`,
    subject: "Commercial General Liability policy (illustrative)",
    footer: `${FOOTER} Policy ${p.policyNumber}`,
  });
  masthead(w, {
    reference: `Policy ${p.policyNumber}`,
    title: "Commercial General Liability Declarations",
    subtitle: "Occurrence form  ·  Excess & surplus lines",
    right: [`Issued ${usDate(todayIso(p.boundAt))}  ·  Binder ${p.binderNumber}`],
  });
  parties(w, "Named insured and mailing address  ·  Producer", [p.insuredName, ...p.insuredAddress], p.producer);

  w.heading("Policy period");
  w.row("From / to", `${usDate(p.effectiveDate)} to ${usDate(p.expirationDate)}, 12:01 a.m. standard time at the mailing address`);

  w.heading("Limits of insurance");
  limitsBlock(w, p);

  w.heading("Classification schedule");
  w.text("Code", { size: 8, bold: true, color: MUTED });
  w.text("Classification", { x: 100, size: 8, bold: true, color: MUTED });
  w.text("Premium basis", { x: 330, size: 8, bold: true, color: MUTED });
  w.text("Premium", { right: 558, size: 8, bold: true, color: MUTED });
  w.y -= 14;
  w.text(p.classCode);
  w.text(p.classDescription, { x: 100 });
  w.text(`Gross receipts ${money(p.grossReceipts)}`, { x: 330 });
  w.text(money(p.premium), { right: 558 });
  w.y -= 14;
  w.para(`Operations: ${p.operations}. States of operation: ${p.states.join(", ")}.`, { size: 8.5, color: MUTED });

  w.heading("Premium");
  premiumBlock(w, p);
  w.text("Premium is fully earned at inception; the policy fee is not refundable.", { size: 8, color: MUTED });
  w.y -= 6;

  w.heading("Forms and endorsements forming part of this policy (illustrative)");
  for (const f of p.forms) w.para(`•  ${f}`, { size: 8.5 });

  surplusLinesNotice(w);

  w.newPage();
  w.heading("Common policy conditions (abridged, illustrative)");
  const conditions: [string, string][] = [
    ["Cancellation", "The first named insured may cancel by written notice. The company may cancel for non-payment of premium "
      + "with 10 days' notice, or for other reasons permitted by law with 30 days' notice. Earned premium is not refunded."],
    ["Subjectivities", "Coverage was bound subject to the subjectivities on binder " + p.binderNumber + ". Any not received by "
      + "their due date may lead the company to amend or cancel coverage."],
    ["Changes", "This policy can only be changed by an endorsement issued by the company."],
    ["Premium audit", "Premium is based on the estimated gross receipts shown. The company may audit actual receipts after "
      + "the policy period; any additional premium is due on audit (no return premium below the minimum)."],
    ["Subcontractors", "Where subcontracted work is permitted, subcontractors must carry general liability limits at least "
      + "equal to this policy's and name the insured as additional insured."],
    ["Representations", "By accepting this policy the insured agrees the statements in the application and submission "
      + "documents are accurate and complete, and that this policy is issued in reliance on them."],
  ];
  for (const [title, text] of conditions) {
    w.ensure(30);
    w.text(title, { bold: true });
    w.y -= 13;
    w.para(text, { size: 9 });
    w.y -= 6;
  }
  w.y -= 24;
  w.text(`Countersigned: ${p.boundBy}`, { size: 9 });
  w.y -= 13;
  w.text(`Underwriting Desktop Specialty  ·  ${usDate(todayIso(p.boundAt))}`, { size: 9, color: MUTED });
  return doc.save();
}
