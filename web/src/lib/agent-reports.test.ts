test("a review report: run, commit, severity sections, statuses, first seen, closed notes", () => {
  const r = parseReport("code", CODE_2);
  assert.equal(r.run, "2026-10-31 20:21");
  assert.equal(r.runAt, "2026-11-01T00:21:00.000Z");   // 8:21 PM Eastern (EDT)
  assert.equal(r.commit, "aa32db3");
  assert.equal(r.previousRun, "2026-10-31 16:12");
  assert.equal(r.headline, "Two commits landed during this run.");
  assert.deepEqual(r.summary?.columns, ["Severity", "Open", "New this run", "Resolved this run"]);
  assert.deepEqual(r.items.map((i) => [i.id, i.severity, i.status, i.statusText, i.firstSeen]), [
    ["CR-066", "Medium", "open", "Open", "2026-10-30"],
    ["CR-095", "Suggestion", "open", "New", null],
  ]);
  assert.deepEqual(r.closed, [{ id: "CR-069", title: "A GL push stamps batches outside a transaction", status: "resolved", note: "resolved in `aa32db3` (SEC-026): one transaction." }]);
});

