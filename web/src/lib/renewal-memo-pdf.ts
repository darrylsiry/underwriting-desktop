import { ACCENT, MUTED, PAGE, RULE, createDocument, masthead, money, parties, surplusLinesNotice, usDate, type Writer } from "./pdf-writer";
import { changeSummary, coverageGapNote, signed, type Comparison } from "./renewal-compare";
import { todayIso } from "./time";

export type RenewalMemo = {
  quoteNumber: string;
  version: number;
  issuedAt: Date;
  validUntil: string;
  issuedBy: string;
  insuredName: string;
  insuredAddress: string[];
  producer: string[];
  expiringPolicyNumber: string;
  expiringPeriod: [string, string];
  renewingPeriod: [string, string];
  comparison: Comparison;
  limits: { label: string; amount: number }[];
  deductible: number;
  classCode: string;
  classDescription: string;
  subjectivities: string[];
};

const RIGHT = PAGE.w - PAGE.margin;
const pctText = (p: number | null) => (p === null ? "" : `${p >= 0 ? "+" : ""}${p}%`);

/** Label, expiring, renewing, change: one row of the three-column money table. */
function moneyRow(w: Writer, label: string, expiring: string, renewing: string, change: string, opts: { bold?: boolean; head?: boolean } = {}) {
  w.ensure(14);
  const size = opts.head ? 8 : 9.5;
  const color = opts.head ? MUTED : undefined;
  w.text(label, { size, bold: opts.bold || opts.head, color: opts.head ? MUTED : (opts.bold ? undefined : MUTED) });
  w.text(expiring, { right: 360, size, bold: opts.bold, color });
  w.text(renewing, { right: 455, size, bold: opts.bold, color });
  w.text(change, { right: RIGHT, size, bold: opts.bold, color });
  w.y -= 14;
}

function bullets(w: Writer, lines: string[], empty: string) {
  if (!lines.length) { w.para(empty, { size: 9.5, color: MUTED }); return; }
  for (const l of lines) w.para(`•  ${l}`, { size: 9.5 });
}

/** The memo that goes to the insured (via the producer) with a renewal quote: what changed and why. */
export async function renderRenewalMemoPdf(m: RenewalMemo): Promise<Uint8Array> {
  const c = m.comparison;
  const b = c.bridge;
  const { doc, w } = await createDocument({
    title: `Renewal memo ${m.quoteNumber} v${m.version} - ${m.insuredName}`,
    subject: "Renewal memorandum (illustrative)",
    footer: `Illustrative renewal memorandum generated by Underwriting Desktop for demonstration only. ${m.quoteNumber} v${m.version}`,
  });
  masthead(w, {
    reference: `Renewal of policy ${m.expiringPolicyNumber}`,
    title: "Renewal Memorandum",
    subtitle: `Commercial General Liability  ·  Quote ${m.quoteNumber} v${m.version}`,
    right: [`${usDate(todayIso(m.issuedAt))}  ·  Quote valid until ${usDate(m.validUntil)}`, `Underwriter: ${m.issuedBy}`],
  });
  parties(w, "Prepared for", [m.insuredName, ...m.insuredAddress], m.producer);

  w.heading("Summary");
  w.para(`Your policy ${m.expiringPolicyNumber} expires on ${usDate(m.expiringPeriod[1])}. We are pleased to offer renewal terms for `
    + `${usDate(m.renewingPeriod[0])} to ${usDate(m.renewingPeriod[1])} under quote ${m.quoteNumber}. The renewal premium is `
    + `${money(b.renewingPremium)}, ${changeSummary(b)} from the expiring premium of ${money(b.expiringPremium)}. `
    + "This memo explains what changed.");
  const gap = coverageGapNote(m.expiringPeriod[1], m.renewingPeriod[0]);
  if (gap) w.para(gap);

  w.heading("Premium");
  moneyRow(w, "", "Expiring", "Renewing", "Change", { head: true });
  for (const r of c.money) {
    moneyRow(w, r.label, money(r.expiring), money(r.renewing), `${signed(r.change)}${r.pct === null ? "" : `  (${pctText(r.pct)})`}`, { bold: r.label === "Total" });
  }
  w.y -= 4;

  w.heading("How the premium change breaks down");
  if (b.termsImpact !== null && b.ratesImpact !== null) {
    w.ensure(60);
    const rows: [string, number][] = [
      ["Expiring premium", b.expiringPremium],
      [`Changes to your operations, coverage and underwriting adjustments`, b.termsImpact],
      [`Changes to our rates (rate revision ${b.rateVersionFrom} to ${b.rateVersionTo})`, b.ratesImpact],
      ["Renewing premium", b.renewingPremium],
    ];
    for (const [i, [label, amount]] of rows.entries()) {
      const edge = i === 0 || i === rows.length - 1;
      w.ensure(14);
      w.text(label, { color: edge ? undefined : MUTED, bold: edge });
      w.text(edge ? money(amount) : signed(amount), { right: RIGHT, bold: edge });
      if (i === rows.length - 2) w.page.drawLine({ start: { x: 380, y: w.y - 4 }, end: { x: RIGHT, y: w.y - 4 }, thickness: 0.6, color: RULE });
      w.y -= 14;
    }
    if (b.rateVersionFrom === b.rateVersionTo) {
      w.para(`Our rates have not changed since your policy was written (rate revision ${b.rateVersionTo}).`, { size: 8.5, color: MUTED });
    }
  } else {
    w.para(`The premium changed by ${signed(b.change)}${b.pct === null ? "" : ` (${pctText(b.pct)})`}. The renewal was rated on rate revision `
      + `${b.rateVersionTo}; your expiring policy was rated on ${b.rateVersionFrom}.`, { size: 9.5 });
  }

  w.heading("Changes to your operations and coverage");
  bullets(w, c.reasons.terms, "No changes to your operations, exposure or coverage terms were reported for this renewal.");

  w.heading("Underwriting adjustments");
  bullets(w, c.reasons.schedule, "Your underwriting credits and debits are unchanged from the expiring policy.");

  w.heading("Rate changes");
  bullets(w, c.reasons.rates, b.rateVersionFrom === b.rateVersionTo
    ? "No rate changes apply: the renewal is rated on the same rate revision as the expiring policy."
    : `The renewal is rated on rate revision ${b.rateVersionTo}; the expiring policy was rated on ${b.rateVersionFrom}.`);

  w.heading("Renewing terms");
  w.row("Policy period", `${usDate(m.renewingPeriod[0])} to ${usDate(m.renewingPeriod[1])}`);
  for (const l of m.limits) w.row(l.label, money(l.amount));
  w.row("Deductible", m.deductible ? money(m.deductible) : "None");
  w.row("Classification", `${m.classCode}  ${m.classDescription}`);

  w.ensure(90);  // keep the heading with its paragraph
  w.heading("Next steps");
  w.para(`Please review the enclosed quotation ${m.quoteNumber}. To bind the renewal, confirm acceptance with your producer before `
    + `${usDate(m.validUntil)}${m.subjectivities.length ? " and provide the following:" : "."}`, { size: 9.5 });
  m.subjectivities.forEach((s, i) => w.para(`${i + 1}.  ${s}`, { size: 9.5 }));

  w.y -= 6;
  w.text("Underwriting Desktop Specialty", { size: 9, bold: true, color: ACCENT });
  w.y -= 12;
  w.text(`Prepared by ${m.issuedBy}`, { size: 9, color: MUTED });
  surplusLinesNotice(w);
  return doc.save();
}
