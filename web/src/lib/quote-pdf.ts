import { MUTED, createDocument, masthead, money, parties, premiumBlock, surplusLinesNotice, usDate } from "./pdf-writer";
import { todayIso } from "./time";

export type QuoteDocument = {
  quoteNumber: string;
  version: number;
  issuedAt: Date;
  validUntil: string;
  issuedBy: string;
  insuredName: string;
  insuredAddress: string[];
  producer: string[];
  effectiveDate: string;
  expirationDate: string;
  limits: { label: string; amount: number }[];
  deductible: number;
  classCode: string;
  classDescription: string;
  operations: string;
  states: string[];
  grossReceipts: number;
  premium: number;
  policyFee: number;
  surplusLinesTax: number;
  surplusLinesTaxRate: number;
  homeState: string;
  total: number;
  rateVersion: string;
  subjectivities: string[];
  forms: string[];
  renewalOf?: string;   // expiring policy number, for a renewal quote
  supersedes?: { version: number; issuedAt: string };   // UX-016: the version this one replaces (issuedAt YYYY-MM-DD)
};

export async function renderQuotePdf(q: QuoteDocument): Promise<Uint8Array> {
  const { doc, w } = await createDocument({
    title: `Quote ${q.quoteNumber} v${q.version} - ${q.insuredName}`,
    subject: "Commercial General Liability quotation (illustrative)",
    // UX-016: the rate-table label is internal detail; it lives in the small footer, not the premium block.
    footer: `Illustrative quotation generated by Underwriting Desktop for demonstration only. Not an offer of insurance. ${q.quoteNumber} v${q.version}  ·  Rated on rate version ${q.rateVersion}`,
  });
  masthead(w, {
    reference: `Quote ${q.quoteNumber}  ·  Version ${q.version}`,
    title: "Commercial General Liability Quotation",
    subtitle: q.renewalOf ? `Renewal of policy ${q.renewalOf}  ·  Excess & surplus lines` : "Excess & surplus lines  ·  Contractors",
    right: [
      `Issued ${usDate(todayIso(q.issuedAt))}  ·  Valid until ${usDate(q.validUntil)}`,
      // UX-016: a broker holding two versions can see which one is live.
      ...(q.supersedes ? [`Supersedes version ${q.supersedes.version} issued ${usDate(q.supersedes.issuedAt)}; that version is withdrawn.`] : []),
      `Underwriter: ${q.issuedBy}`,
    ],
  });
  parties(w, "Named insured and producer", [q.insuredName, ...q.insuredAddress], q.producer);

  w.heading("Policy period");
  w.row("Effective", `${usDate(q.effectiveDate)} to ${usDate(q.expirationDate)}, 12:01 a.m. standard time at the insured's address`);

  w.heading("Coverage and limits (occurrence form)");
  for (const l of q.limits) w.row(l.label, money(l.amount));
  w.row("Deductible (bodily injury and property damage, per occurrence)", q.deductible ? money(q.deductible) : "None");

  w.heading("Classification and exposure");
  w.row("Class", `${q.classCode}  ${q.classDescription}`);
  w.row("Premium basis", `Gross receipts ${money(q.grossReceipts)}`);
  w.row("States of operation", q.states.join(", "));
  w.y -= 2;
  w.para(`Operations: ${q.operations}`, { color: MUTED, size: 8.5 });

  w.heading("Premium");
  premiumBlock(w, q);
  w.text("Premium is fully earned at inception.", { size: 8, color: MUTED });
  w.y -= 6;

  w.heading("Subjectivities (required before binding)");
  q.subjectivities.forEach((s, i) => w.para(`${i + 1}.  ${s}`));

  w.heading("Forms and endorsements (illustrative)");
  for (const f of q.forms) w.para(`•  ${f}`, { size: 8.5 });

  surplusLinesNotice(w);
  return doc.save();
}
