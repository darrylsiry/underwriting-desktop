import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from "pdf-lib";

export type QuoteDocument = {
  quoteNumber: string;
  version: number;
  issuedAt: Date;
  validUntil: string;
  issuedBy: string;
  insuredName: string;
  insuredAddress: string[];
  producer: string[];
  effectiveDate: string;
  expirationDate: string;
  limits: { label: string; amount: number }[];
  deductible: number;
  classCode: string;
  classDescription: string;
  operations: string;
  states: string[];
  grossReceipts: number;
  premium: number;
  policyFee: number;
  surplusLinesTax: number;
  surplusLinesTaxRate: number;
  homeState: string;
  total: number;
  rateVersion: string;
  subjectivities: string[];
  forms: string[];
};

const PAGE = { w: 612, h: 792, margin: 54 };
const INK = rgb(0.06, 0.09, 0.16);
const MUTED = rgb(0.39, 0.45, 0.55);
const RULE = rgb(0.85, 0.88, 0.92);
const ACCENT = rgb(0.31, 0.27, 0.9);

const money = (n: number) => `$${Math.round(n).toLocaleString("en-US")}`;
const usDate = (iso: string) => {
  const [y, m, d] = iso.split("-");
  return `${m}/${d}/${y}`;
};

/** Standard PDF fonts only encode WinAnsi; replace anything else so drawing never throws. */
export function pdfSafe(text: string): string {
  return text
    .replace(/[‐-‒]/g, "-")
    .replace(/[→]/g, "->")
    .replace(/[^\x20-\x7E -ÿ–—‘’“”•…€]/g, "?");
}

class Writer {
  page!: PDFPage;
  y = 0;
  constructor(private doc: PDFDocument, private font: PDFFont, private bold: PDFFont, private footer: string) {
    this.newPage();
  }

  newPage() {
    this.page = this.doc.addPage([PAGE.w, PAGE.h]);
    this.y = PAGE.h - PAGE.margin;
    this.page.drawText(pdfSafe(this.footer), { x: PAGE.margin, y: 28, size: 7, font: this.font, color: MUTED });
  }

  ensure(space: number) {
    if (this.y - space < PAGE.margin) this.newPage();
  }

  text(s: string, opts: { x?: number; size?: number; bold?: boolean; color?: typeof INK; right?: number } = {}) {
    const size = opts.size ?? 9.5;
    const font = opts.bold ? this.bold : this.font;
    const t = pdfSafe(s);
    const x = opts.right !== undefined ? opts.right - font.widthOfTextAtSize(t, size) : opts.x ?? PAGE.margin;
    this.page.drawText(t, { x, y: this.y, size, font, color: opts.color ?? INK });
  }

  /** Word-wrapped paragraph; returns after moving y below it. */
  para(s: string, opts: { x?: number; width?: number; size?: number; color?: typeof INK; bold?: boolean } = {}) {
    const size = opts.size ?? 9.5;
    const font = opts.bold ? this.bold : this.font;
    const x = opts.x ?? PAGE.margin;
    const width = opts.width ?? PAGE.w - PAGE.margin - x;
    let line = "";
    for (const word of pdfSafe(s).split(/\s+/)) {
      const next = line ? `${line} ${word}` : word;
      if (font.widthOfTextAtSize(next, size) > width && line) {
        this.ensure(size + 3);
        this.page.drawText(line, { x, y: this.y, size, font, color: opts.color ?? INK });
        this.y -= size + 3;
        line = word;
      } else {
        line = next;
      }
    }
    if (line) {
      this.ensure(size + 3);
      this.page.drawText(line, { x, y: this.y, size, font, color: opts.color ?? INK });
      this.y -= size + 3;
    }
  }

  heading(s: string) {
    this.ensure(40);
    this.y -= 14;
    this.text(s.toUpperCase(), { size: 8, bold: true, color: ACCENT });
    this.y -= 5;
    this.page.drawLine({ start: { x: PAGE.margin, y: this.y }, end: { x: PAGE.w - PAGE.margin, y: this.y }, thickness: 0.6, color: RULE });
    this.y -= 13;
  }

  row(label: string, value: string, opts: { bold?: boolean } = {}) {
    this.ensure(14);
    this.text(label, { color: MUTED, bold: opts.bold });
    this.text(value, { right: PAGE.w - PAGE.margin, bold: opts.bold });
    this.y -= 14;
  }
}

export async function renderQuotePdf(q: QuoteDocument): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(`Quote ${q.quoteNumber} v${q.version} - ${pdfSafe(q.insuredName)}`);
  doc.setSubject("Commercial General Liability quotation (illustrative)");
  doc.setCreator("Underwriting Desktop");
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const w = new Writer(doc, font, bold,
    `Illustrative quotation generated by Underwriting Desktop for demonstration only. Not an offer of insurance. ${q.quoteNumber} v${q.version}`);
  const right = PAGE.w - PAGE.margin;

  // Masthead
  w.text("UNDERWRITING DESKTOP SPECIALTY", { size: 9, bold: true, color: ACCENT });
  w.text(`Quote ${q.quoteNumber}  ·  Version ${q.version}`, { right, size: 9, bold: true });
  w.y -= 20;
  w.text("Commercial General Liability Quotation", { size: 18, bold: true });
  w.y -= 14;
  w.text("Excess & surplus lines  ·  Contractors", { size: 9.5, color: MUTED });
  w.text(`Issued ${usDate(q.issuedAt.toISOString().slice(0, 10))}  ·  Valid until ${usDate(q.validUntil)}`,
    { right, size: 9.5, color: MUTED });
  w.y -= 12;
  w.text(`Underwriter: ${q.issuedBy}`, { right, size: 9.5, color: MUTED });

  // Parties
  w.heading("Named insured and producer");
  const top = w.y;
  w.text(q.insuredName, { bold: true });
  w.y -= 13;
  for (const line of q.insuredAddress) { w.text(line); w.y -= 13; }
  const leftBottom = w.y;
  w.y = top;
  for (const [i, line] of q.producer.entries()) { w.text(line, { x: 330, bold: i === 0 }); w.y -= 13; }
  w.y = Math.min(leftBottom, w.y);

  w.heading("Policy period");
  w.row("Effective", `${usDate(q.effectiveDate)} to ${usDate(q.expirationDate)}, 12:01 a.m. standard time at the insured's address`);

  w.heading("Coverage and limits (occurrence form)");
  for (const l of q.limits) w.row(l.label, money(l.amount));
  w.row("Deductible (bodily injury and property damage, per occurrence)", q.deductible ? money(q.deductible) : "None");

  w.heading("Classification and exposure");
  w.row("Class", `${q.classCode}  ${q.classDescription}`);
  w.row("Premium basis", `Gross receipts ${money(q.grossReceipts)}`);
  w.row("States of operation", q.states.join(", "));
  w.y -= 2;
  w.para(`Operations: ${q.operations}`, { color: MUTED, size: 8.5 });

  w.heading("Premium");
  w.row("Premium", money(q.premium));
  w.row("Policy fee", money(q.policyFee));
  w.row(`Surplus lines tax and fees (${q.homeState}, ${(q.surplusLinesTaxRate * 100).toFixed(2)}%)`, money(q.surplusLinesTax));
  w.page.drawLine({ start: { x: 380, y: w.y + 10 }, end: { x: right, y: w.y + 10 }, thickness: 0.6, color: RULE });
  w.y -= 2;
  w.row("Total", money(q.total), { bold: true });
  w.text(`Premium is fully earned at inception. Rated on rate version ${q.rateVersion}.`, { size: 8, color: MUTED });
  w.y -= 6;

  w.heading("Subjectivities (required before binding)");
  q.subjectivities.forEach((s, i) => w.para(`${i + 1}.  ${s}`));

  w.heading("Forms and endorsements (illustrative)");
  for (const f of q.forms) w.para(`•  ${f}`, { size: 8.5 });

  w.heading("Surplus lines notice");
  w.para("This insurance is placed with an insurer not licensed in the insured's home state and is not protected by "
    + "the state insurance guaranty fund. Surplus lines tax is the responsibility of the surplus lines licensee.",
    { size: 8, color: MUTED });


  return doc.save();
}
